"""Build a Kaggle notebook that runs one step of Part 2 next to the Challenge 2026 data:

    python kaggle/build_notebook.py <step> <output folder>
    kaggle kernels push -p <output folder>

The Challenge data is about 1.2 TB, so it is never downloaded: the heavy steps run on Kaggle,
where the data is mounted, and only their small outputs come back to data/hsp_large/.
Kaggle notebooks here run without internet, so the generated script carries the project's
packages inside it, installs the EDF reader from a wheel uploaded as a private dataset
(omkarpuri/edfio-wheel), rebuilds the package folders and then runs the step.

Steps:
  features  cognitive.features: 49 numbers per night            -> hsp_features.csv
  epochs    cognitive.epochs:   one row of 71 numbers per epoch -> epochs/epochs_*.npz
  deep      cognitive.deep:     train and score the deep model  -> results/cognitive/hsp_large_deep_report.txt
            (inputs: the epochs notebook's output, and hsp_features.csv with demographics.csv
            uploaded as the private dataset omkarpuri/hsp-large-table)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ["common", "sleep_staging", "cognitive"]
CHALLENGE_DATA = "physionet/physionetchallenge2026datalargeversion"

# Run once inside the notebook, before the step: put hsp_features.csv, demographics.csv and the
# epoch packs in one folder, the layout cognitive.deep expects. It sits outside /kaggle/working so
# the 830 MB of packs are not saved again as output.
LINK_DEEP_INPUTS = '''
data = Path("/tmp/hsp_large"); (data / "epochs").mkdir(parents=True, exist_ok=True)
for name in ("hsp_features.csv", "demographics.csv"):
    found = glob.glob(f"/kaggle/input/**/hsp-large-table/**/{name}", recursive=True) or glob.glob(f"/kaggle/input/**/{name}", recursive=True)
    print(name, "<-", found[0]); os.symlink(found[0], data / name)
packs = sorted(glob.glob("/kaggle/input/**/epochs_*.npz", recursive=True))
print(len(packs), "epoch packs")
for pack in packs:
    os.symlink(pack, data / "epochs" / os.path.basename(pack))
'''

STEPS = {
    "features": {"slug": "hsp-features-large", "module": "cognitive.features", "gpu": False,
                 "args": ["/kaggle/input", "--out", "/kaggle/working/hsp_features.csv", "--workers", "4"],
                 "datasets": ["omkarpuri/edfio-wheel", CHALLENGE_DATA], "kernels": []},
    "epochs": {"slug": "hsp-epochs-large", "module": "cognitive.epochs", "gpu": False,
               "args": ["/kaggle/input", "--out", "/kaggle/working/epochs", "--workers", "4"],
               "datasets": ["omkarpuri/edfio-wheel", CHALLENGE_DATA], "kernels": []},
    "deep": {"slug": "hsp-deep-large", "module": "cognitive.deep", "gpu": True, "args": ["/tmp/hsp_large"],
             "datasets": ["omkarpuri/edfio-wheel", "omkarpuri/hsp-large-table"],
             "kernels": ["omkarpuri/hsp-epochs-large"], "setup": LINK_DEEP_INPUTS},
}


def build(step: str, out: Path) -> None:
    spec = STEPS[step]
    sources = {str(path.relative_to(ROOT).as_posix()): path.read_text(encoding="utf-8")
               for package in PACKAGES for path in sorted((ROOT / package).glob("*.py"))}
    code = f'''# Generated by kaggle/build_notebook.py ({step}): installs the EDF reader without internet,
# writes the project packages, then runs {spec["module"]}.
import glob, os, runpy, subprocess, sys
from pathlib import Path
wheels = glob.glob("/kaggle/input/**/edfio*.whl", recursive=True)
if wheels:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-index", "--no-deps", wheels[0]], check=True)
SOURCES = {sources!r}
for name, text in SOURCES.items():
    Path("/kaggle/working", name).parent.mkdir(parents=True, exist_ok=True)
    Path("/kaggle/working", name).write_text(text)
{spec.get("setup", "")}
os.chdir("/kaggle/working"); sys.path.insert(0, "/kaggle/working")
sys.argv = {[spec["module"]] + spec["args"]!r}
runpy.run_module("{spec["module"]}", run_name="__main__", alter_sys=True)
'''
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{spec['slug']}.py").write_text(code, encoding="utf-8")
    meta = {"id": f"omkarpuri/{spec['slug']}", "title": spec["slug"], "code_file": f"{spec['slug']}.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": spec["gpu"],
            "enable_tpu": False, "enable_internet": False, "dataset_sources": spec["datasets"],
            "kernel_sources": spec["kernels"], "competition_sources": [], "model_sources": []}
    if spec["gpu"]:
        meta["machine_shape"] = "NvidiaTeslaT4"
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"Wrote {out / meta['code_file']} and kernel-metadata.json. Push with: kaggle kernels push -p {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in STEPS:
        sys.exit(f"usage: python kaggle/build_notebook.py {{{'|'.join(STEPS)}}} <output folder>")
    build(sys.argv[1], Path(sys.argv[2]))
